/** Helper to filter aircraft available for a given game year */
export function getAvailableAircraft(year: number, historicalRestrictions: boolean): readonly HistoricalAircraft[] {
  if (!historicalRestrictions) return AIRCRAFT_DATABASE;
  return AIRCRAFT_DATABASE.filter((ac) => ac.introductionYear <= year);
}

/** Helper to look up an aircraft by its unique identifier */
export function findAircraftById(id: string): HistoricalAircraft | undefined {
  return AIRCRAFT_DATABASE.find((ac) => ac.id === id);
}
